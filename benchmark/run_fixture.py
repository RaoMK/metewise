"""Benchmark metewise against the local fixture app -- no Docker needed.

Spins up fixtures/vuln_app.py, drives a short two-user session, runs metewise
(reads + writes + destructive), and scores the result against the ground truth
in expectations/fixture.json. Prints precision / recall / F1 and exits non-zero
if anything was missed or wrongly flagged.

    python3 benchmark/run_fixture.py            # print the report
    python3 benchmark/run_fixture.py --write-results   # also update results/
"""

from __future__ import annotations

import importlib.util
import pathlib
import sys
import threading
from http.server import ThreadingHTTPServer

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "src"))

from metewise import http  # noqa: E402
from metewise.model import Exchange, Principal  # noqa: E402

from harness import collect_findings  # noqa: E402
from score import Expectations, report, score  # noqa: E402

ALICE_INV = "3f1a9c22-0000-4000-8000-000000000001"
BOB_INV = "7b2e5d44-0000-4000-8000-000000000002"


def _load_fixture():
    spec = importlib.util.spec_from_file_location(
        "vuln_app", ROOT / "fixtures" / "vuln_app.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _observe(base: str):
    """Drive a realistic two-user session and record it as Exchanges."""
    a, b = {"X-User": "alice"}, {"X-User": "bob"}

    def real(method, path, hdrs, body=None):
        st, _, rb = http.request(method, base + path, hdrs, body)
        return Exchange(method=method, url=base + path, principal=hdrs["X-User"],
                        status=st, req_body=body, resp_body=rb)

    def note(method, path, hdrs, status, resp=None, body=None):
        # Record an endpoint's existence without executing a destructive call.
        return Exchange(method=method, url=base + path, principal=hdrs["X-User"],
                        status=status, req_body=body, resp_body=resp)

    return [
        real("GET", f"/invoices/{ALICE_INV}", a),
        real("GET", f"/safe-invoices/{ALICE_INV}", a),
        real("GET", "/shared/pubdoc-terms-v3", a),
        real("GET", f"/invoices/{BOB_INV}", b),
        real("POST", "/invoices", a, {"total": 10.0, "customer_email": "seed@acme.example"}),
        note("PUT", f"/invoices/{ALICE_INV}", a, 200, {"id": ALICE_INV}, {"total": 4820.0}),
        note("DELETE", f"/invoices/{ALICE_INV}", a, 204),
        note("PUT", f"/safe-invoices/{ALICE_INV}", a, 200, {"id": ALICE_INV}, {"total": 1.0}),
        note("DELETE", f"/safe-invoices/{ALICE_INV}", a, 204),
    ]


def run() -> tuple:
    mod = _load_fixture()
    srv = ThreadingHTTPServer(("127.0.0.1", 0), mod.Handler)
    base = f"http://127.0.0.1:{srv.server_address[1]}"
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    try:
        principals = {
            "alice": Principal("alice", tenant="acme", headers={"X-User": "alice"}),
            "bob": Principal("bob", tenant="globex", headers={"X-User": "bob"}),
        }
        found = collect_findings(_observe(base), principals,
                                 write=True, allow_destructive=True)
    finally:
        srv.shutdown()
        srv.server_close()
    exp = Expectations.load(str(HERE / "expectations" / "fixture.json"))
    return score(found, exp), found


def _write_results(s) -> None:
    out = HERE / "results" / "fixture.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(
        f"# Benchmark results — {s.name}\n\n"
        f"Generated by `benchmark/run_fixture.py` against `fixtures/vuln_app.py`.\n\n"
        f"| metric | value |\n|---|---|\n"
        f"| precision | {s.precision:.0%} |\n"
        f"| recall | {s.recall:.0%} |\n"
        f"| f1 | {s.f1:.0%} |\n"
        f"| true positives | {len(s.true_positives)} |\n"
        f"| false positives | {len(s.false_positives)} |\n"
        f"| false negatives | {len(s.false_negatives)} |\n\n"
        f"Planted bugs caught: "
        f"{', '.join(f'{m} {t}' for m, t in sorted(s.true_positives))}.\n"
    )
    print(f"wrote {out}")


def main() -> int:
    s, _ = run()
    print(report(s))
    if "--write-results" in sys.argv:
        _write_results(s)
    return 0 if s.perfect else 1


if __name__ == "__main__":
    raise SystemExit(main())
